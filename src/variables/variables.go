func EnabledWallboxFilters() []string {
	filters := make([]string, 0, len(WallboxApiCalls))
	for _, apiCall := range WallboxApiCalls {
		if apiCall.Enabled {
			filters = append(filters, apiCall.Filter)
		}
	}
	return filters
}

